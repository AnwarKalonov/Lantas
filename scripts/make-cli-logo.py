#!/usr/bin/env python3
"""Turn public/logo.png into the terminal banner used by cli/lantas.mjs.

Each output character packs two vertical pixels: the high two bits are the top
pixel's intensity (0-3), the low two bits are the bottom pixel's. The CLI draws
them with half blocks, so the thin cloud ridges keep their shape without a
raster dependency.

A plain resample is not enough: the ridges are a couple of pixels wide, and at
this width they cover a small part of a cell, so their average disappears and
the enclosure turns into a blob. Each cell is scored from the mean of its
brightest tenth together with its overall mean — the peak holds the dashes, the
mean keeps the heavy letters from flattening into one slab.

    python3 scripts/make-cli-logo.py
"""

from __future__ import annotations

import pathlib

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "public" / "logo.png"
OUT = ROOT / "cli" / "logo.mjs"

WIDTH = 82
THRESHOLDS = (0.13, 0.33, 0.58)  # blank / faint / mid / full
PEAK = 0.55


def level(value: float) -> int:
    if value < THRESHOLDS[0]:
        return 0
    if value < THRESHOLDS[1]:
        return 1
    if value < THRESHOLDS[2]:
        return 2
    return 3


def main() -> None:
    image = Image.open(SOURCE).convert("RGBA")
    box = image.getchannel("A").point(lambda value: 255 if value > 20 else 0).getbbox()
    if box:
        image = image.crop(box)
    alpha = image.getchannel("A")
    width, height_px = alpha.size
    height = max(6, round(WIDTH * height_px / width / 2))
    cell_w = width / WIDTH
    cell_h = height_px / (height * 2)
    pixels = alpha.load()

    def score(x0: float, x1: float, y0: float, y1: float) -> float:
        values = []
        for y in range(int(y0), max(int(y0) + 1, int(y1))):
            for x in range(int(x0), max(int(x0) + 1, int(x1))):
                values.append(pixels[min(width - 1, x), min(height_px - 1, y)] / 255)
        if not values:
            return 0.0
        values.sort(reverse=True)
        top = values[: max(1, len(values) // 10)]
        blended = (sum(top) / len(top)) * PEAK + (sum(values) / len(values)) * (1 - PEAK)
        return blended ** 1.25

    rows = []
    for y in range(height):
        row = ""
        for x in range(WIDTH):
            left = x * cell_w
            top_edge = y * 2 * cell_h
            top = level(score(left, left + cell_w, top_edge, top_edge + cell_h))
            bottom = level(score(left, left + cell_w, top_edge + cell_h, top_edge + 2 * cell_h))
            row += format(top * 4 + bottom, "x")
        rows.append(row)

    body = "\n".join(f'  "{row}",' for row in rows)
    OUT.write_text(
        "// Generated by scripts/make-cli-logo.py — the dashed cloud and LANTAS letters.\n"
        "// Each character is one terminal cell: high two bits are the top pixel's\n"
        "// intensity (0-3), low two bits are the bottom pixel's. Rendering with half\n"
        "// blocks keeps the logo's thin dashed ridges without a raster library.\n\n"
        f"export const LOGO_WIDTH = {WIDTH};\n"
        f"export const LOGO_HEIGHT = {height};\n"
        "export const LOGO_ROWS = [\n"
        f"{body}\n"
        "];\n",
        encoding="utf8",
    )
    print(f"wrote {OUT.relative_to(ROOT)} ({WIDTH}x{height})")


if __name__ == "__main__":
    main()
